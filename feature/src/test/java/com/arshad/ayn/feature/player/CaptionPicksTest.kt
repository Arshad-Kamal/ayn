package com.arshad.ayn.feature.player

import com.arshad.ayn.core.access.recorded
import com.arshad.ayn.core.access.CaptionCue
import com.arshad.ayn.core.access.CaptionTrack
import com.arshad.ayn.core.access.VideoId
import com.arshad.ayn.core.access.captions.RecordedCaptions
import com.arshad.ayn.core.access.newpipe.FIXED_VIDEO_ID
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/** The default track (Q52) on the recorded video's six tracks (en, en auto, de-DE, ja, pt-BR,
 *  es-419), and the cue at a position on the recorded manual track's cues. */
class CaptionPicksTest {

    private val recorded: List<CaptionTrack> by lazy { recorded("video") { video(VideoId(FIXED_VIDEO_ID)) }.captionTracks }

    private fun recordedTrack(languageTag: String, auto: Boolean = false): CaptionTrack =
        recorded.single { it.languageTag == languageTag && it.autoGenerated == auto }

    @Test
    fun theWrittenTrackInTheLanguageComesBeforeYouTubesAutomaticOne() {
        assertEquals(recordedTrack("en"), defaultCaptionTrack(recorded, "en"))
        assertEquals(recordedTrack("en"), defaultCaptionTrack(recorded.reversed(), "en"))
    }

    @Test
    fun anAutomaticTrackIsTakenWhenNoneIsWritten() {
        assertEquals(recordedTrack("en", auto = true), defaultCaptionTrack(recorded - recordedTrack("en"), "en"))
    }

    @Test
    fun regionsMatchEitherWay() {
        assertEquals(recordedTrack("en"), defaultCaptionTrack(recorded, "en-GB"))
        assertEquals(recordedTrack("de-DE"), defaultCaptionTrack(recorded, "de"))
        assertEquals(recordedTrack("pt-BR"), defaultCaptionTrack(recorded, "pt"))
        assertEquals(recordedTrack("es-419"), defaultCaptionTrack(recorded, "ES"))
    }

    @Test
    fun theFirstMatchingTrackWinsWhateverItsRegion() {
        val british = track("en-GB")
        val plain = track("en")

        assertEquals(british, defaultCaptionTrack(listOf(british, plain), "en"))
        assertEquals(plain, defaultCaptionTrack(listOf(plain, british), "en-GB"))
    }

    @Test
    fun withdrawnCodesMatchTheirSuccessors() {
        listOf("iw" to "he", "in" to "id", "ji" to "yi").forEach { (old, new) ->
            assertEquals(old, defaultCaptionTrack(listOf(track(old)), new)?.languageTag)
            assertEquals(new, defaultCaptionTrack(listOf(track(new)), old)?.languageTag)
            assertEquals("$new-XX", defaultCaptionTrack(listOf(track("$new-XX")), old)?.languageTag)
        }
    }

    @Test
    fun offOrALanguageWithoutATrackPicksNone() {
        assertNull(defaultCaptionTrack(recorded, null))
        assertNull(defaultCaptionTrack(recorded, "bn"))
        assertNull(defaultCaptionTrack(emptyList(), "en"))
        // Codes match whole, never as a prefix.
        assertNull(defaultCaptionTrack(recorded, "eng"))
    }

    @Test
    fun theCueAtAPositionIsTheOneSpanningIt() {
        val (first, second, third) = RecordedCaptions.MANUAL_FIRST_CUES
        val cues = RecordedCaptions.MANUAL_FIRST_CUES

        assertNull(cues.cueAt(0))
        assertEquals(first, cues.cueAt(first.startMs))
        assertEquals(first, cues.cueAt(first.endMs - 1))
        assertNull(cues.cueAt(first.endMs))
        assertEquals(second, cues.cueAt(20_000))
        assertEquals(third, cues.cueAt(third.endMs - 1))
        assertNull(cues.cueAt(third.endMs))
        assertNull(emptyList<CaptionCue>().cueAt(1_000))
    }

    private fun track(languageTag: String): CaptionTrack =
        CaptionTrack(languageTag, languageTag, autoGenerated = false, url = "https://www.youtube.com/api/timedtext?lang=$languageTag")
}
