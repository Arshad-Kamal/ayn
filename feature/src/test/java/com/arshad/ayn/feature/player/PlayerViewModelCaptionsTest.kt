/**
 * The player's captions (M7-D14, Q51–Q54) on the recorded video's six tracks, the English ones
 * answered with their recorded TTML through the real `TimedTextCaptions` and every other language
 * with YouTube's 404: the profile's default track per turn, a pick or Off for the video, each
 * track fetched once a turn, Try again, and no captions on a Short (Robolectric: Media3's TTML
 * parser reads through Android's XML parser).
 */
@RunWith(RobolectricTestRunner::class)
class PlayerViewModelCaptionsTest {

    private val dispatcher = StandardTestDispatcher()
    private val settings = FakeProfileSettingsStore(selectedId = PROFILE)
    private var settingsStore: ProfileSettingsStore = settings
    private val recorded = RecordedCaptions.source()

    /** Every track the player asked the seam for, in order. */
    private val asked = mutableListOf<CaptionTrack>()
    private var captionSource: CaptionSource = CaptionSource { track ->
        asked += track
        recorded.cues(track)
    }

    private val tracks: List<CaptionTrack> by lazy { recorded("video") { video(VideoId(FIXED_VIDEO_ID)) }.captionTracks }
    private val manual: CaptionTrack get() = tracks.single { it.languageTag == "en" && !it.autoGenerated }
    private val auto: CaptionTrack get() = tracks.single { it.languageTag == "en" && it.autoGenerated }
    private val german: CaptionTrack get() = tracks.single { it.languageTag == "de-DE" }

    @Before
    fun setUp() {
        Dispatchers.setMain(dispatcher)
    }

    @After
    fun tearDown() {
        Dispatchers.resetMain()
    }

    private fun player(shorts: ShortsList? = null): PlayerViewModel = PlayerViewModel(
        opening = testVideo(FIXED_VIDEO_ID),
        playAll = null,
        extractor = UnsupportedExtractor("captions"),
        store = FakeSubscriptionStore(),
        watchStore = FakeWatchStore(),
        playlistStore = FakePlaylistStore(),
        settingsStore = settingsStore,
        voteSource = RecordedVotes.source {},
        captionSource = captionSource,
        liveChat = FakeLiveChat(),
        shorts = shorts,
        compute = Dispatchers.Main,
    )

    private fun captionsLanguage(language: String?) {
        settings.byProfile.value = mapOf(PROFILE to ProfileSettings(captionsLanguage = language))
    }

    private fun PlayerViewModel.captions(): PlayerCaptions? = uiState.value.captions

    private fun CaptionCues?.cueCount(): Int = (this as CaptionCues.Shown).cues.size

    private fun CaptionCues?.firstCues(count: Int): List<CaptionCue> = (this as CaptionCues.Shown).cues.take(count)

    @Test
    fun anEnglishProfileStartsOnTheWrittenEnglishTrack() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()

        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        val captions = viewModel.captions()!!
        assertEquals(tracks, captions.tracks)
        assertEquals(manual, captions.chosen)
        assertEquals(RecordedCaptions.MANUAL_CUE_COUNT, captions.cues.cueCount())
        assertEquals(RecordedCaptions.MANUAL_FIRST_CUES, captions.cues.firstCues(3))
        assertNull(captions.missingLanguage)
        assertEquals(listOf(manual), asked)
    }

    @Test
    fun theCuesShowAsLoadingUntilTheyArrive() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        viewModel.chooseCaptions(auto)

        assertEquals(auto, viewModel.captions()!!.chosen)
        assertEquals(CaptionCues.Loading, viewModel.captions()!!.cues)
        advanceUntilIdle()
        assertEquals(RecordedCaptions.AUTO_FIRST_CUES, viewModel.captions()!!.cues.firstCues(4))
    }

    @Test
    fun captionsOffAsksForNothing() = runTest(dispatcher) {
        val viewModel = player()
        advanceUntilIdle()

        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        assertEquals(PlayerCaptions(tracks, chosen = null, cues = null, language = null), viewModel.captions())
        assertEquals(emptyList<CaptionTrack>(), asked)
    }

    @Test
    fun aDefaultLanguageTheVideoLacksStartsOffAndIsNamed() = runTest(dispatcher) {
        captionsLanguage("bn")
        val viewModel = player()
        advanceUntilIdle()

        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        assertEquals(PlayerCaptions(tracks, chosen = null, cues = null, language = "bn"), viewModel.captions())
        assertEquals("bn", viewModel.captions()!!.missingLanguage)
        assertEquals(emptyList<CaptionTrack>(), asked)
    }

    @Test
    fun aVideoWithoutTracksNamesTheMissingDefaultToo() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()

        viewModel.captionsResolved(0, emptyList())
        advanceUntilIdle()

        assertEquals(PlayerCaptions(emptyList(), chosen = null, cues = null, language = "en"), viewModel.captions())
        assertEquals("en", viewModel.captions()!!.missingLanguage)
    }

    @Test
    fun eachTrackIsFetchedOnceInATurn() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        // Back to the fetched track while the other's fetch runs, then to that one again: it
        // waits for the running fetch.
        viewModel.chooseCaptions(auto)
        viewModel.chooseCaptions(manual)
        viewModel.chooseCaptions(auto)
        advanceUntilIdle()
        // Both fetched: each shows from what was kept.
        viewModel.chooseCaptions(manual)
        val manualAgain = viewModel.captions()!!.cues
        viewModel.chooseCaptions(auto)

        assertEquals(RecordedCaptions.MANUAL_FIRST_CUES, manualAgain.firstCues(3))
        assertEquals(RecordedCaptions.AUTO_FIRST_CUES, viewModel.captions()!!.cues.firstCues(4))
        assertEquals(listOf(manual, auto), asked)
    }

    @Test
    fun offForTheVideoLeavesTheProfileDefault() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        viewModel.chooseCaptions(null)

        assertNull(viewModel.captions()!!.chosen)
        assertNull(viewModel.captions()!!.cues)
        assertEquals("en", settings.of(PROFILE).captionsLanguage)
        assertEquals(emptyList<Long>(), settings.updatedIds)
    }

    @Test
    fun aTrackTheVideoDoesNotListChangesNothing() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        val before = viewModel.captions()

        viewModel.chooseCaptions(manual.copy(url = "https://www.youtube.com/api/timedtext?v=other&lang=en"))
        advanceUntilIdle()

        assertEquals(before, viewModel.captions())
        assertEquals(1, asked.size)
    }

    @Test
    fun aFailedFetchShowsFailedAndTryAgainAsksAgain() = runTest(dispatcher) {
        captionsLanguage("de")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        assertEquals(german, viewModel.captions()!!.chosen)
        assertEquals(CaptionCues.Failed(serial = 1), viewModel.captions()!!.cues)

        viewModel.retryCaptions()
        assertEquals(CaptionCues.Loading, viewModel.captions()!!.cues)
        advanceUntilIdle()

        // A failure of its own, so the screen's note shows again.
        assertEquals(CaptionCues.Failed(serial = 2), viewModel.captions()!!.cues)
        assertEquals(listOf(german, german), asked)
    }

    @Test
    fun tryAgainShowsTheCuesOnceTheFetchSucceeds() = runTest(dispatcher) {
        var failing = true
        captionSource = CaptionSource { track -> if (failing) CaptionLookup.Failed else recorded.cues(track) }
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        assertEquals(CaptionCues.Failed(serial = 1), viewModel.captions()!!.cues)

        failing = false
        viewModel.retryCaptions()
        advanceUntilIdle()

        assertEquals(RecordedCaptions.MANUAL_CUE_COUNT, viewModel.captions()!!.cues.cueCount())
    }

    @Test
    fun tryAgainDoesNothingUnlessTheFetchFailed() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        viewModel.retryCaptions()
        advanceUntilIdle()

        assertEquals(1, asked.size)
    }

    @Test
    fun settingsThatCannotBeReadStartOff() = runTest(dispatcher) {
        settingsStore = object : ProfileSettingsStore {
            override fun settings(): Flow<ProfileSettingsState> = flow { throw IOException("disk") }
            override suspend fun update(profileId: Long, transform: (ProfileSettings) -> ProfileSettings) = false
        }
        val viewModel = player()
        advanceUntilIdle()

        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        assertEquals(PlayerCaptions(tracks, chosen = null, cues = null, language = null), viewModel.captions())
        assertEquals(emptyList<CaptionTrack>(), asked)
    }

    @Test
    fun tracksReportedBeforeTheSettingsAnswerWaitForThem() = runTest(dispatcher) {
        captionsLanguage("en")
        settings.selected.value = null
        val viewModel = player()
        advanceUntilIdle()

        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        assertNull(viewModel.captions())

        settings.selected.value = PROFILE
        advanceUntilIdle()
        assertEquals(manual, viewModel.captions()!!.chosen)
    }

    @Test
    fun aTurnThatEndsBeforeTheSettingsAnswerStartsNoCaptions() = runTest(dispatcher) {
        captionsLanguage("en")
        settings.selected.value = null
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        viewModel.play(testVideo("bbbbbbbbbbb"))
        settings.selected.value = PROFILE
        advanceUntilIdle()

        assertNull(viewModel.captions())
        assertEquals(emptyList<CaptionTrack>(), asked)
    }

    /** YouTube's links are signed and expire: a re-resolve's fresh ones serve Try again. */
    @Test
    fun aReResolveRefreshesTheLinksAndKeepsThePick() = runTest(dispatcher) {
        val fresh = tracks.map { it.copy(url = it.url + "&fresh=1") }
        captionSource = CaptionSource { track ->
            asked += track
            if (track.url.endsWith("&fresh=1")) recorded.cues(track) else CaptionLookup.Failed
        }
        captionsLanguage("de")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        viewModel.chooseCaptions(auto)
        advanceUntilIdle()
        assertEquals(CaptionCues.Failed(serial = 2), viewModel.captions()!!.cues)

        viewModel.captionsResolved(0, fresh)
        assertEquals(fresh[tracks.indexOf(auto)], viewModel.captions()!!.chosen)
        viewModel.retryCaptions()
        advanceUntilIdle()

        assertEquals(fresh, viewModel.captions()!!.tracks)
        assertEquals(RecordedCaptions.AUTO_FIRST_CUES, viewModel.captions()!!.cues.firstCues(4))
        assertEquals(listOf(german, auto, fresh[tracks.indexOf(auto)]), asked)
    }

    @Test
    fun aDifferentListLaterInTheTurnChangesNothing() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        viewModel.chooseCaptions(auto)
        advanceUntilIdle()

        viewModel.captionsResolved(0, tracks.reversed())
        advanceUntilIdle()

        assertEquals(tracks, viewModel.captions()!!.tracks)
        assertEquals(auto, viewModel.captions()!!.chosen)
        assertEquals(2, asked.size)
    }

    @Test
    fun aShortShowsNoCaptions() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player(shorts = ShortsList(emptyList()))
        advanceUntilIdle()

        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()

        assertNull(viewModel.captions())
        assertEquals(emptyList<CaptionTrack>(), asked)
    }

    @Test
    fun aNewTurnDropsTheCaptionsAndALateAnswerForTheLastVideo() = runTest(dispatcher) {
        val answer = CompletableDeferred<CaptionLookup>()
        captionSource = CaptionSource { withContext(NonCancellable) { answer.await() } }
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        assertEquals(CaptionCues.Loading, viewModel.captions()!!.cues)

        viewModel.play(testVideo("bbbbbbbbbbb"))
        answer.complete(CaptionLookup.Found(emptyList()))
        advanceUntilIdle()

        assertNull(viewModel.captions())
    }

    @Test
    fun onlyThePlayingTurnsReportCounts() = runTest(dispatcher) {
        captionsLanguage("en")
        val viewModel = player()
        advanceUntilIdle()
        viewModel.play(testVideo("bbbbbbbbbbb"))

        viewModel.captionsResolved(0, tracks)
        advanceUntilIdle()
        assertNull(viewModel.captions())
        viewModel.captionsResolved(1, tracks)
        advanceUntilIdle()

        assertEquals(RecordedCaptions.MANUAL_CUE_COUNT, viewModel.captions()!!.cues.cueCount())
        assertEquals(listOf(manual), asked)
    }
}

private const val PROFILE = 1L
