package com.arshad.ayn.feature.player

import com.arshad.ayn.core.access.CaptionCue
import com.arshad.ayn.core.access.CaptionLookup
import com.arshad.ayn.core.access.CaptionSource
import com.arshad.ayn.core.access.CaptionTrack
import com.arshad.ayn.feature.sameLanguage
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.ensureActive
import kotlinx.coroutines.job
import kotlinx.coroutines.launch

/** The turn's captions (M7-D14): what the CC control, the Playback sheet's Captions row and the
 *  Captions sheet show, and the cues drawn over the video. */
data class PlayerCaptions(
    /** The video's tracks in YouTube's order; empty when it has none. */
    val tracks: List<CaptionTrack>,
    /** The track shown; `null` for Off. */
    val chosen: CaptionTrack?,
    /** The chosen track's cues; `null` while captions are Off. */
    val cues: CaptionCues?,
    /** The profile's captions language, its default for every video; `null` for Off. */
    val language: String?,
) {
    /** [language] when the video has no track in it, so captions started Off (Q51: "No Bengali
     *  captions for this video"); `null` when one matched or the default is Off. */
    val missingLanguage: String?
        get() = language.takeIf { defaultCaptionTrack(tracks, it) == null }
}

sealed interface CaptionCues {
    data object Loading : CaptionCues

    /** In time order, never overlapping ([cueAt]). */
    data class Shown(val cues: List<CaptionCue>) : CaptionCues

    /** Couldn't be fetched or read (a rate limit, an expired link): the ccfail note, Try again.
     *  [serial] counts the turn's failed fetches, so each failure is a note of its own. */
    data class Failed(val serial: Int) : CaptionCues
}

/**
 * The track a video starts on for a profile whose captions language is [language] (Q52): the first
 * track in that language whatever the region (en matches en-GB either way; iw, in and ji match
 * he, id and yi), one written by people before YouTube's automatic one. `null` for Off, or when no
 * track is in [language].
 */
fun defaultCaptionTrack(tracks: List<CaptionTrack>, language: String?): CaptionTrack? {
    if (language == null) return null
    val inLanguage = tracks.filter { sameLanguage(it.languageTag, language) }
    return inLanguage.firstOrNull { !it.autoGenerated } ?: inLanguage.firstOrNull()
}

/** The cue showing at [positionMs], `null` between cues; the cues are in time order and never
 *  overlap, as [CaptionLookup.Found] hands them. */
fun List<CaptionCue>.cueAt(positionMs: Long): CaptionCue? {
    val index = binarySearch { cue ->
        when {
            positionMs < cue.startMs -> 1
            positionMs >= cue.endMs -> -1
            else -> 0
        }
    }
    return getOrNull(index)
}

/**
 * One turn's captions (M7-D14): they start on the profile's default track ([defaultCaptionTrack]),
 * a chosen track's cues are fetched once and kept for the turn (a failed fetch is forgotten, so Try
 * again asks again; a track picked again while its fetch runs waits for that fetch), and every
 * change is [publish]ed. Fetches run in a child scope of [parent]; [close] cancels them with the
 * turn, so no late answer reaches the next video.
 */
internal class TurnCaptions(
    tracks: List<CaptionTrack>,
    language: String?,
    private val source: CaptionSource,
    parent: CoroutineScope,
    private val publish: (PlayerCaptions) -> Unit,
) {
    private val scope = CoroutineScope(parent.coroutineContext + SupervisorJob(parent.coroutineContext.job))

    /** Cues fetched, and fetches running, by the track's place in the list, which [refresh] keeps. */
    private val found = mutableMapOf<Int, List<CaptionCue>>()
    private val running = mutableSetOf<Int>()
    private var failures = 0
    private var state: PlayerCaptions

    init {
        val default = defaultCaptionTrack(tracks, language)
        state = PlayerCaptions(tracks, chosen = null, cues = null, language = language)
        choose(default)
    }

    /** Shows [track] (`null`: Off) for the rest of the turn; the profile's default is unchanged. A
     *  track this video doesn't list (a pick from an earlier turn's list) changes nothing. */
    fun choose(track: CaptionTrack?) {
        if (track == null) return update(state.copy(chosen = null, cues = null))
        val index = state.tracks.indexOf(track)
        if (index < 0) return
        val cues = found[index]
        update(state.copy(chosen = track, cues = if (cues != null) CaptionCues.Shown(cues) else CaptionCues.Loading))
        if (cues == null && running.add(index)) fetch(index)
    }

    /** Try again on the ccfail note: the chosen track's cues are asked for afresh. */
    fun retry() {
        if (state.cues is CaptionCues.Failed) choose(state.chosen)
    }

    /**
     * Another resolve of the turn's video listed [tracks]: when they are the same tracks with fresh
     * links (YouTube's are signed and expire), later fetches (Try again, a first pick) use those;
     * what shows stays. A different list changes nothing.
     */
    fun refresh(tracks: List<CaptionTrack>) {
        val sameTracks = tracks.size == state.tracks.size &&
            tracks.zip(state.tracks).all { (fresh, old) -> fresh.copy(url = old.url) == old }
        if (!sameTracks) return
        update(state.copy(tracks = tracks, chosen = state.chosen?.let { tracks[state.tracks.indexOf(it)] }))
    }

    fun close() {
        scope.cancel()
    }

    private fun fetch(index: Int) {
        scope.launch {
            val lookup = source.cues(state.tracks[index])
            // The lookup may not have noticed a cancel by [close].
            ensureActive()
            running -= index
            if (lookup is CaptionLookup.Found) found[index] = lookup.cues
            if (state.chosen == state.tracks[index]) update(state.copy(cues = lookup.toCues()))
        }
    }

    private fun update(captions: PlayerCaptions) {
        state = captions
        publish(captions)
    }

    private fun CaptionLookup.toCues(): CaptionCues = when (this) {
        is CaptionLookup.Found -> CaptionCues.Shown(cues)
        CaptionLookup.Failed -> CaptionCues.Failed(++failures)
    }
}
