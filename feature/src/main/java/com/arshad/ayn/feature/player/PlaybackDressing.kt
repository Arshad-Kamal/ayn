package com.arshad.ayn.feature.player

import android.os.Bundle
import com.arshad.ayn.core.access.CaptionTrack
import com.arshad.ayn.core.access.Chapter
import com.arshad.ayn.core.access.LiveChatSeed
import com.arshad.ayn.core.access.Segment
import com.arshad.ayn.core.access.SegmentCategory
import com.arshad.ayn.core.access.SegmentLookup
import com.arshad.ayn.core.access.Storyboard
import com.arshad.ayn.core.access.VideoId
import com.arshad.ayn.core.access.VideoItem
import com.arshad.ayn.core.access.VideoMetadata
import kotlin.time.Instant

/**
 * What the player shows beyond the opening card, read from the video page the service's resolve
 * fetched: the uploader (its avatar, and its name and link, which a search Short's card lacks),
 * the chapters, one storyboard level for the scrub preview, the page's related videos (the
 * Related row and Up next, M5-D12), what Details adds (subscribers, YouTube's likes, the
 * description), the SponsorBlock lookup the resolve ran beside it (M7-D3), the caption tracks
 * (M7-D14), and whether the page is live ([live], the screen's live chrome: LIVE-D23) and since
 * when ([liveStartedAt], LIVE-D24), and its chat's seed ([liveChat], LIVE-D6; none under
 * Restricted Mode, LIVE-D25). It rides the resolved item's `MediaMetadata.extras`
 * ([toBundle]), so the screen gets it with the item and needs no second extraction; the item a
 * controller sets before the resolve lands carries none ([fromBundle] answers `null`), which tells
 * the screen the item is still masked.
 */
data class PlaybackDressing(
    val uploaderAvatarUrl: String?,
    val chapters: List<Chapter>,
    /** The largest level YouTube offers: the preview is drawn at about 400 px wide. */
    val storyboard: Storyboard?,
    /** In YouTube's order; empty when the page offers none. */
    val relatedVideos: List<VideoItem> = emptyList(),
    /** `null` when no lookup ran (SponsorBlock off, every category Off, or a Short: Q40). */
    val segments: SegmentLookup? = null,
    /** `null` when the page hides it or it can't be read. */
    val subscriberCount: Long? = null,
    /** YouTube's own count (M7-D5); `null` when the video hides it or it can't be read. */
    val likeCount: Long? = null,
    val description: String? = null,
    val uploaderName: String? = null,
    val uploaderUrl: String? = null,
    /** In YouTube's order; empty when the video has none. */
    val captionTracks: List<CaptionTrack> = emptyList(),
    /** The page was an active live stream when resolved ([VideoMetadata.isLive]). */
    val live: Boolean = false,
    /** [VideoMetadata.liveStartedAt]. */
    val liveStartedAt: Instant? = null,
    /** [VideoMetadata.liveChat]: the page's chat, as the profile may see it. */
    val liveChat: LiveChatSeed? = null,
) {
    /** As a player shows it: a live page without what only a video's chrome shows (chapters, the
     *  storyboard, SponsorBlock: `live-tv-player`, `live-phone-player`); its related videos stay
     *  (LIVE-D24). */
    fun forScreen(): PlaybackDressing = if (live) copy(chapters = emptyList(), storyboard = null, segments = null) else this

    fun toBundle(): Bundle = Bundle().apply {
        putBoolean(KEY_DRESSED, true)
        putString(KEY_AVATAR, uploaderAvatarUrl)
        putString(KEY_CHANNEL_NAME, uploaderName)
        putString(KEY_CHANNEL_URL, uploaderUrl)
        putStringArrayList(KEY_CHAPTER_TITLES, ArrayList(chapters.map { it.title }))
        putLongArray(KEY_CHAPTER_STARTS, chapters.map { it.startSeconds }.toLongArray())
        storyboard?.let { board ->
            putStringArrayList(KEY_BOARD_PAGES, ArrayList(board.pageUrls))
            putInt(KEY_FRAME_WIDTH, board.frameWidth)
            putInt(KEY_FRAME_HEIGHT, board.frameHeight)
            putInt(KEY_FRAME_COUNT, board.frameCount)
            putInt(KEY_FRAME_DURATION_MS, board.frameDurationMs)
            putInt(KEY_FRAMES_PER_PAGE_X, board.framesPerPageX)
            putInt(KEY_FRAMES_PER_PAGE_Y, board.framesPerPageY)
        }
        putParcelableArrayList(KEY_RELATED, relatedVideos.mapTo(ArrayList(relatedVideos.size), ::videoBundle))
        segments?.let { putSegments(it) }
        subscriberCount?.let { putLong(KEY_SUBSCRIBERS, it) }
        likeCount?.let { putLong(KEY_LIKES, it) }
        putString(KEY_DESCRIPTION, description)
        putStringArrayList(KEY_CAPTION_LANGUAGES, ArrayList(captionTracks.map { it.languageTag }))
        putStringArrayList(KEY_CAPTION_NAMES, ArrayList(captionTracks.map { it.name }))
        putBooleanArray(KEY_CAPTION_AUTO, captionTracks.map { it.autoGenerated }.toBooleanArray())
        putStringArrayList(KEY_CAPTION_URLS, ArrayList(captionTracks.map { it.url }))
        putBoolean(KEY_ITEM_LIVE, live)
        liveStartedAt?.let { putLong(KEY_LIVE_STARTED_MS, it.toEpochMilliseconds()) }
        liveChat?.let {
            putString(KEY_CHAT_TOKEN, it.token)
            putBoolean(KEY_CHAT_REPLAY, it.replay)
        }
    }

    private fun Bundle.putSegments(lookup: SegmentLookup) {
        when (lookup) {
            is SegmentLookup.Found -> {
                putString(KEY_SEGMENTS, SEGMENTS_FOUND)
                putStringArrayList(KEY_SEGMENT_CATEGORIES, ArrayList(lookup.segments.map { it.category.key }))
                putLongArray(KEY_SEGMENT_STARTS, lookup.segments.map { it.startMs }.toLongArray())
                putLongArray(KEY_SEGMENT_ENDS, lookup.segments.map { it.endMs }.toLongArray())
            }
            SegmentLookup.None -> putString(KEY_SEGMENTS, SEGMENTS_NONE)
            SegmentLookup.Failed -> putString(KEY_SEGMENTS, SEGMENTS_FAILED)
        }
    }

    companion object {
        fun from(metadata: VideoMetadata, segments: SegmentLookup? = null): PlaybackDressing = PlaybackDressing(
            uploaderAvatarUrl = metadata.uploaderAvatarUrl,
            chapters = metadata.chapters,
            storyboard = metadata.storyboards.lastOrNull(),
            relatedVideos = metadata.relatedVideos,
            segments = segments,
            subscriberCount = metadata.uploaderSubscriberCount,
            likeCount = metadata.likeCount,
            description = metadata.description,
            uploaderName = metadata.uploaderName,
            uploaderUrl = metadata.uploaderUrl,
            captionTracks = metadata.captionTracks,
            live = metadata.isLive,
            liveStartedAt = metadata.liveStartedAt,
            liveChat = metadata.liveChat,
        )

        /** The dressing a resolved item carries; `null` for an item that never passed a resolve. */
        fun fromBundle(extras: Bundle?): PlaybackDressing? {
            if (extras == null || !extras.getBoolean(KEY_DRESSED)) return null
            val titles = extras.getStringArrayList(KEY_CHAPTER_TITLES).orEmpty()
            val starts = extras.getLongArray(KEY_CHAPTER_STARTS) ?: LongArray(0)
            return PlaybackDressing(
                uploaderAvatarUrl = extras.getString(KEY_AVATAR),
                chapters = titles.zip(starts.asList()) { title, start -> Chapter(title, start) },
                storyboard = storyboardFrom(extras),
                relatedVideos = relatedFrom(extras),
                segments = segmentsFrom(extras),
                subscriberCount = extras.longOrNull(KEY_SUBSCRIBERS),
                likeCount = extras.longOrNull(KEY_LIKES),
                description = extras.getString(KEY_DESCRIPTION),
                uploaderName = extras.getString(KEY_CHANNEL_NAME),
                uploaderUrl = extras.getString(KEY_CHANNEL_URL),
                captionTracks = captionTracksFrom(extras),
                live = extras.getBoolean(KEY_ITEM_LIVE),
                liveStartedAt = extras.longOrNull(KEY_LIVE_STARTED_MS)?.let(Instant::fromEpochMilliseconds),
                liveChat = extras.getString(KEY_CHAT_TOKEN)?.let { LiveChatSeed(it, extras.getBoolean(KEY_CHAT_REPLAY)) },
            )
        }

        private fun captionTracksFrom(extras: Bundle): List<CaptionTrack> {
            val languages = extras.getStringArrayList(KEY_CAPTION_LANGUAGES).orEmpty()
            val names = extras.getStringArrayList(KEY_CAPTION_NAMES).orEmpty()
            val auto = extras.getBooleanArray(KEY_CAPTION_AUTO) ?: BooleanArray(0)
            val urls = extras.getStringArrayList(KEY_CAPTION_URLS).orEmpty()
            return (0 until minOf(languages.size, names.size, auto.size, urls.size)).map { i ->
                CaptionTrack(languages[i], names[i], auto[i], urls[i])
            }
        }

        private fun Bundle.longOrNull(key: String): Long? = if (containsKey(key)) getLong(key) else null

        private fun segmentsFrom(extras: Bundle): SegmentLookup? = when (extras.getString(KEY_SEGMENTS)) {
            SEGMENTS_NONE -> SegmentLookup.None
            SEGMENTS_FAILED -> SegmentLookup.Failed
            SEGMENTS_FOUND -> {
                val categories = extras.getStringArrayList(KEY_SEGMENT_CATEGORIES).orEmpty()
                val starts = extras.getLongArray(KEY_SEGMENT_STARTS) ?: LongArray(0)
                val ends = extras.getLongArray(KEY_SEGMENT_ENDS) ?: LongArray(0)
                val segments = (0 until minOf(categories.size, starts.size, ends.size)).mapNotNull { i ->
                    SegmentCategory.of(categories[i])?.let { Segment(it, starts[i], ends[i]) }
                }
                if (segments.isEmpty()) SegmentLookup.None else SegmentLookup.Found(segments)
            }
            else -> null
        }

        // The typed overload is API 33 (minSdk 30); every element is a Bundle this class wrote.
        @Suppress("DEPRECATION")
        private fun relatedFrom(extras: Bundle): List<VideoItem> =
            extras.getParcelableArrayList<Bundle>(KEY_RELATED).orEmpty().mapNotNull(::videoFrom)

        private fun videoBundle(video: VideoItem): Bundle = Bundle().apply {
            putString(KEY_ID, video.id.value)
            putString(KEY_TITLE, video.title)
            putString(KEY_UPLOADER_NAME, video.uploaderName)
            putString(KEY_UPLOADER_URL, video.uploaderUrl)
            putLong(KEY_DURATION, video.durationSeconds)
            putLong(KEY_VIEWS, video.viewCount)
            putString(KEY_TEXTUAL_DATE, video.textualUploadDate)
            video.uploadDate?.let { putLong(KEY_UPLOAD_MS, it.toEpochMilliseconds()) }
            putString(KEY_THUMBNAIL, video.thumbnailUrl)
            putBoolean(KEY_LIVE, video.isLive)
        }

        /** `null` for an entry without a valid id (never written so; a bundle isn't a type). */
        private fun videoFrom(bundle: Bundle): VideoItem? {
            val id = bundle.getString(KEY_ID)?.takeIf(VideoId::isValid) ?: return null
            return VideoItem(
                id = VideoId(id),
                title = bundle.getString(KEY_TITLE).orEmpty(),
                uploaderName = bundle.getString(KEY_UPLOADER_NAME),
                uploaderUrl = bundle.getString(KEY_UPLOADER_URL),
                durationSeconds = bundle.getLong(KEY_DURATION),
                viewCount = bundle.getLong(KEY_VIEWS, -1),
                textualUploadDate = bundle.getString(KEY_TEXTUAL_DATE),
                uploadDate = if (bundle.containsKey(KEY_UPLOAD_MS)) Instant.fromEpochMilliseconds(bundle.getLong(KEY_UPLOAD_MS)) else null,
                thumbnailUrl = bundle.getString(KEY_THUMBNAIL),
                isLive = bundle.getBoolean(KEY_LIVE),
            )
        }

        private fun storyboardFrom(extras: Bundle): Storyboard? {
            val pages = extras.getStringArrayList(KEY_BOARD_PAGES) ?: return null
            return Storyboard(
                pageUrls = pages.toList(),
                frameWidth = extras.getInt(KEY_FRAME_WIDTH),
                frameHeight = extras.getInt(KEY_FRAME_HEIGHT),
                frameCount = extras.getInt(KEY_FRAME_COUNT),
                frameDurationMs = extras.getInt(KEY_FRAME_DURATION_MS),
                framesPerPageX = extras.getInt(KEY_FRAMES_PER_PAGE_X),
                framesPerPageY = extras.getInt(KEY_FRAMES_PER_PAGE_Y),
            )
        }

        private const val KEY_DRESSED = "ke.dressed"
        private const val KEY_AVATAR = "ke.avatar"
        private const val KEY_CHANNEL_NAME = "ke.channelName"
        private const val KEY_CHANNEL_URL = "ke.channelUrl"
        private const val KEY_CHAPTER_TITLES = "ke.chapterTitles"
        private const val KEY_CHAPTER_STARTS = "ke.chapterStarts"
        private const val KEY_BOARD_PAGES = "ke.boardPages"
        private const val KEY_FRAME_WIDTH = "ke.frameWidth"
        private const val KEY_FRAME_HEIGHT = "ke.frameHeight"
        private const val KEY_FRAME_COUNT = "ke.frameCount"
        private const val KEY_FRAME_DURATION_MS = "ke.frameDurationMs"
        private const val KEY_FRAMES_PER_PAGE_X = "ke.framesPerPageX"
        private const val KEY_FRAMES_PER_PAGE_Y = "ke.framesPerPageY"
        private const val KEY_RELATED = "ke.related"
        private const val KEY_SEGMENTS = "ke.segments"
        private const val KEY_SEGMENT_CATEGORIES = "ke.segmentCategories"
        private const val KEY_SEGMENT_STARTS = "ke.segmentStarts"
        private const val KEY_SEGMENT_ENDS = "ke.segmentEnds"
        private const val KEY_SUBSCRIBERS = "ke.subscribers"
        private const val KEY_LIKES = "ke.likes"
        private const val KEY_DESCRIPTION = "ke.description"
        private const val KEY_CAPTION_LANGUAGES = "ke.captionLanguages"
        private const val KEY_CAPTION_NAMES = "ke.captionNames"
        private const val KEY_CAPTION_AUTO = "ke.captionAuto"
        private const val KEY_CAPTION_URLS = "ke.captionUrls"
        private const val KEY_ITEM_LIVE = "ke.live"
        private const val KEY_LIVE_STARTED_MS = "ke.liveStartedMs"
        private const val KEY_CHAT_TOKEN = "ke.chatToken"
        private const val KEY_CHAT_REPLAY = "ke.chatReplay"
        private const val SEGMENTS_FOUND = "found"
        private const val SEGMENTS_NONE = "none"
        private const val SEGMENTS_FAILED = "failed"
        private const val KEY_ID = "id"
        private const val KEY_TITLE = "title"
        private const val KEY_UPLOADER_NAME = "uploaderName"
        private const val KEY_UPLOADER_URL = "uploaderUrl"
        private const val KEY_DURATION = "durationSeconds"
        private const val KEY_VIEWS = "viewCount"
        private const val KEY_TEXTUAL_DATE = "textualUploadDate"
        private const val KEY_UPLOAD_MS = "uploadDateMs"
        private const val KEY_THUMBNAIL = "thumbnailUrl"
        private const val KEY_LIVE = "isLive"
    }
}
