/**
 * Captions in the player (M7-D14, `b3-player-panels` cc* and cues* states) through the real shell,
 * [com.arshad.ayn.feature.player.PlayerViewModel] and the recorded Enigma page's two English tracks,
 * whose cues come from the recorded TTML ([RecordedCaptions]: the manual track's second cue runs
 * 18.64–21.88 s).
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34], qualifiers = "w960dp-h540dp")
class PlayerCaptionsTest {

    private companion object {
        const val PROFILE = 1L
        const val CUE_MS = 19_000L
        const val CUE = "♪ We're no strangers to love ♪"
        const val FAILED = "English captions didn’t load · the video plays on"
        const val PROMPT_SKIP = "Skip to 2:14"
    }

    @get:Rule
    val compose = createAndroidComposeRule<ComponentActivity>()

    private val settings = FakeProfileSettingsStore(selectedId = PROFILE)
    private val watch = FakeWatchStore()
    private var captions: CaptionSource = RecordedCaptions.source()
    private lateinit var service: FakePlaybackService
    private lateinit var navController: NavHostController

    private val manual: CaptionTrack get() = RecordedEnigmaPage.captionTracks.single { !it.autoGenerated }

    private val card = VideoItem(
        id = VideoId(CHAPTERS_VIDEO_ID),
        title = RecordedEnigmaPage.title,
        uploaderName = RecordedEnigmaPage.uploaderName,
        uploaderUrl = RecordedEnigmaPage.uploaderUrl,
        durationSeconds = 2861,
        viewCount = 15_000_000,
        textualUploadDate = "12 days ago",
        uploadDate = null,
        thumbnailUrl = null,
        isLive = false,
    )

    @Before
    fun setUp() {
        installOfflineImageLoader(compose.activity)
        service = FakePlaybackService(compose.activity)
    }

    @After
    fun tearDown() {
        service.release()
    }

    private fun captionsLanguage(language: String?) {
        settings.byProfile.value = mapOf(PROFILE to ProfileSettings(captionsLanguage = language))
    }

    /** Opens the player and lets the stream land, playing [atMs] in, its tracks reported. */
    private fun play(atMs: Long = CUE_MS) {
        compose.setContent {
            navController = rememberNavController()
            TestShell(
                extractor = ChannelExtractor(),
                profileSettings = settings,
                watchStore = watch,
                captions = captions,
                playerSession = { service.session.token },
                navController = navController,
            )
        }
        compose.waitForIdle()
        compose.runOnUiThread { navController.navigate(PlayerRoute(card)) }
        repeat(20) { if (service.player.requested.isEmpty() || !service.player.isPlayWhenReady) compose.waitForIdle() }
        compose.runOnUiThread { service.player.ready(atMs) }
        repeat(3) { compose.waitForIdle() }
    }

    private fun press(code: Int) {
        compose.onRoot().performKeyPress(KeyEvent(AndroidKeyEvent(AndroidKeyEvent.ACTION_DOWN, code)))
        compose.onRoot().performKeyPress(KeyEvent(AndroidKeyEvent(AndroidKeyEvent.ACTION_UP, code)))
        compose.waitForIdle()
    }

    /** BACK as the remote sends it (see `PlayerScreenTest.remoteBack`). */
    private fun remoteBack() {
        compose.onRoot().performKeyPress(KeyEvent(AndroidKeyEvent(AndroidKeyEvent.ACTION_DOWN, AndroidKeyEvent.KEYCODE_BACK)))
        compose.waitForIdle()
        compose.pressBack()
        compose.onRoot().performKeyPress(KeyEvent(AndroidKeyEvent(AndroidKeyEvent.ACTION_UP, AndroidKeyEvent.KEYCODE_BACK)))
        compose.waitForIdle()
    }

    /** Lets the cue tick and the 200 ms lift run. */
    private fun settle() {
        compose.mainClock.advanceTimeBy(400)
        compose.waitForIdle()
    }

    private fun row(label: String): SemanticsMatcher = hasText(label) and hasClickAction()
    private fun control(label: String): SemanticsMatcher = hasContentDescription(label) and hasClickAction()

    @Test
    fun `an English profile shows the written track's cue at the position`() {
        captionsLanguage("en")
        play()
        settle()

        compose.onNodeWithText(CUE).assertExists()
    }

    @Test
    fun `the cue sits low with the chrome hidden and rises above the chrome while it shows`() {
        captionsLanguage("en")
        play()
        press(AndroidKeyEvent.KEYCODE_DPAD_UP) // Pause to the scrub bar, the chrome's top
        settle()
        val chromeTop = compose.onNode(isFocused()).getUnclippedBoundsInRoot().top
        val risen = compose.onNodeWithText(CUE).getUnclippedBoundsInRoot()
        assertEquals((chromeTop - 36.dp - 2.5.dp).value, risen.bottom.value, 1f)

        compose.pressBack()
        settle()

        val screen = compose.onRoot().getUnclippedBoundsInRoot()
        val low = compose.onNodeWithText(CUE).getUnclippedBoundsInRoot()
        // The text's bounds sit inside its well's 2.5 dp foot padding.
        assertEquals((screen.bottom - 46.dp - 2.5.dp).value, low.bottom.value, 1f)
    }

    @Test
    fun `the cue rises over a skip prompt, and Details hides it`() {
        captionsLanguage("en")
        service.segments = runBlocking { RecordedSegments.lookup() }
        play()
        compose.pressBack()
        settle()
        compose.onNodeWithText(PROMPT_SKIP).assertExists()
        val screen = compose.onRoot().getUnclippedBoundsInRoot()
        assertEquals((screen.bottom - 46.dp - 75.dp - 2.5.dp).value, compose.onNodeWithText(CUE).getUnclippedBoundsInRoot().bottom.value, 1f)

        press(AndroidKeyEvent.KEYCODE_DPAD_UP) // shows the chrome
        compose.onNode(control("More")).dpadSelect()
        compose.waitForIdle()
        compose.onNode(row("Video details")).dpadSelect()
        settle()

        compose.onNodeWithText(CUE).assertDoesNotExist()
    }

    @Test
    fun `the cue follows the position, and a seek into a gap clears it`() {
        captionsLanguage("en")
        play()
        compose.pressBack()
        settle()
        compose.onNodeWithText(CUE).assertExists()

        press(AndroidKeyEvent.KEYCODE_DPAD_LEFT) // 19 s to 9 s, between the recorded cues
        settle()

        compose.onNodeWithText(CUE).assertDoesNotExist()
    }

    @Test
    fun `with captions Off, OK on CC opens the Captions sheet on Off, and a pick shows its cues and returns to CC`() {
        play()
        settle()
        compose.onNodeWithText(CUE).assertDoesNotExist()

        compose.onNode(control("Captions")).dpadSelect()
        compose.waitForIdle()
        compose.onNodeWithText("Just for this video; your default (Off) is in Settings\u00A0›\u00A0Playback.").assertExists()
        compose.onNode(row("Made by YouTube’s speech recognition")).assert(hasText("English (auto-generated)"))
        compose.onNode(row("Off")).assertIsFocused()
        press(AndroidKeyEvent.KEYCODE_DPAD_DOWN)
        compose.onNode(row("English")).assertIsFocused().dpadSelect()
        compose.waitForIdle()
        settle()

        compose.onNodeWithText("Just for this video", substring = true).assertDoesNotExist()
        compose.onNode(control("Captions")).assertIsFocused()
        compose.onNodeWithText(CUE).assertExists()
    }

    @Test
    fun `the Captions sheet opens on the chosen track, and BACK returns to CC, captions unchanged`() {
        captionsLanguage("en")
        play()
        compose.onNode(control("Captions")).dpadSelect()
        compose.waitForIdle()
        compose.onNode(row("English")).assertIsFocused()

        compose.pressBack()

        compose.onNode(control("Captions")).assertIsFocused()
        settle()
        compose.onNodeWithText(CUE).assertExists()
    }

    @Test
    fun `a pick from the Playback sheet's Captions closes every panel and returns to More`() {
        play()
        compose.onNode(control("More")).dpadSelect()
        compose.waitForIdle()
        compose.onNode(row("Captions")).dpadSelect()
        compose.waitForIdle()
        press(AndroidKeyEvent.KEYCODE_DPAD_DOWN)
        compose.onNode(row("English")).assertIsFocused().dpadSelect()
        compose.waitForIdle()

        compose.onNodeWithText("Playing now").assertDoesNotExist()
        compose.onNode(control("More")).assertIsFocused()
    }

    @Test
    fun `a default the video lacks shows Off with its line, and the Captions sheet names it`() {
        captionsLanguage("bn")
        play()
        compose.onNode(control("More")).dpadSelect()
        compose.waitForIdle()

        compose.onNode(row("Captions")).assert(hasText("Off")).assert(hasText("No Bengali captions for this video"))
        press(AndroidKeyEvent.KEYCODE_DPAD_DOWN)
        press(AndroidKeyEvent.KEYCODE_DPAD_DOWN)
        compose.onNode(row("Captions")).assertIsFocused().dpadSelect()
        compose.waitForIdle()
        compose.onNodeWithText("Just for this video. It has no Bengali captions, your default in Settings\u00A0›\u00A0Playback.").assertExists()

        compose.pressBack()
        compose.onNode(row("Captions")).assertIsFocused()
    }

    @Test
    fun `the Playback sheet names the chosen track`() {
        captionsLanguage("en")
        play()
        compose.onNode(control("More")).dpadSelect()
        compose.waitForIdle()

        compose.onNode(row("Captions")).assert(hasText(manual.name))
    }

    @Test
    fun `a video without tracks has focus pass over CC and the Playback row, which says so`() {
        service.page = RecordedEnigmaPage.copy(captionTracks = emptyList())
        play()

        press(AndroidKeyEvent.KEYCODE_DPAD_RIGHT) // Pause to Forward 10 seconds
        press(AndroidKeyEvent.KEYCODE_DPAD_RIGHT)
        compose.onNode(control("Comments")).assertIsFocused()
        press(AndroidKeyEvent.KEYCODE_DPAD_RIGHT)
        compose.onNode(control("Speed")).assertIsFocused()
        press(AndroidKeyEvent.KEYCODE_DPAD_RIGHT)
        compose.onNode(control("Quality")).assertIsFocused()
        press(AndroidKeyEvent.KEYCODE_DPAD_RIGHT)
        compose.onNode(control("More")).assertIsFocused().dpadSelect()
        compose.waitForIdle()
        compose.onNodeWithText("None for this video").assertExists()
        press(AndroidKeyEvent.KEYCODE_DPAD_DOWN)
        press(AndroidKeyEvent.KEYCODE_DPAD_DOWN)

        compose.onNode(isFocused()).assert(hasText("SponsorBlock"))
    }

    @Test
    fun `captions that didn't load say so over the hidden chrome, each failure again, and Try again shows them`() {
        var asked = 0
        val recorded = RecordedCaptions.source()
        captions = CaptionSource { track -> if (++asked <= 2) CaptionLookup.Failed else recorded.cues(track) }
        captionsLanguage("en")
        play()
        compose.onNodeWithText(FAILED).assertDoesNotExist() // the chrome holds the corner

        compose.pressBack()
        compose.onNodeWithText(FAILED).assertExists()
        press(AndroidKeyEvent.KEYCODE_DPAD_CENTER) // fails again, at once
        compose.onNodeWithText(FAILED).assertExists()
        press(AndroidKeyEvent.KEYCODE_DPAD_CENTER)
        settle()

        assertEquals(3, asked)
        compose.onNodeWithText(FAILED).assertDoesNotExist()
        compose.onNodeWithText(CUE).assertExists()
        assertTrue("OK retried instead of pausing", service.player.isPlayWhenReady)
    }

    @Test
    fun `BACK hides the failed note and stays on the player`() {
        captions = CaptionSource { CaptionLookup.Failed }
        captionsLanguage("en")
        play()
        compose.pressBack()
        compose.onNodeWithText(FAILED).assertExists()

        remoteBack()
        settle()

        compose.onNodeWithText(FAILED).assertDoesNotExist()
        assertTrue(navController.currentBackStackEntry?.destination?.route?.contains("PlayerRoute") == true)
        press(AndroidKeyEvent.KEYCODE_DPAD_UP) // the chrome shows, then hides
        compose.pressBack()
        settle()
        compose.onNodeWithText(FAILED).assertDoesNotExist()
    }

    @Test
    fun `another key drops the failed note and acts as usual`() {
        captions = CaptionSource { CaptionLookup.Failed }
        captionsLanguage("en")
        play()
        compose.pressBack()
        compose.onNodeWithText(FAILED).assertExists()

        press(AndroidKeyEvent.KEYCODE_DPAD_LEFT) // the chrome stays hidden
        settle()

        compose.onNodeWithText(FAILED).assertDoesNotExist()
        assertEquals((CUE_MS - 10_000).toDouble(), service.player.seeks.single().toDouble(), 1_000.0)
    }

    @Test
    fun `a dismissed note stays gone when the stage comes back in the turn, and the next video's failure shows its own`() {
        captions = CaptionSource { CaptionLookup.Failed }
        captionsLanguage("en")
        play()
        compose.pressBack()
        remoteBack()
        compose.onNodeWithText(FAILED).assertDoesNotExist()

        compose.runOnUiThread { service.player.end() }
        compose.waitForIdle()
        compose.onNode(row("Cancel")).dpadSelect() // Up next gives the stage back
        compose.waitForIdle()
        compose.pressBack() // hides the chrome on Replay
        settle()
        compose.onNodeWithText(FAILED).assertDoesNotExist()

        compose.runOnUiThread { navController.playerViewModel().play(RecordedEnigmaPage.relatedVideos.first()) }
        repeat(5) { compose.waitForIdle() }
        compose.runOnUiThread { service.player.ready(CUE_MS) }
        repeat(3) { compose.waitForIdle() }
        compose.pressBack()
        settle()

        compose.onNodeWithText(FAILED).assertExists()
    }

    @Test
    fun `the resumed toast keeps the corner, and the failed note shows once it goes`() {
        captions = CaptionSource { CaptionLookup.Failed }
        captionsLanguage("en")
        watch.resumePointsMs[card.id] = CUE_MS
        play()
        compose.onNodeWithText("Resumed at 0:19").assertExists()
        compose.onNodeWithText(FAILED).assertDoesNotExist()

        compose.mainClock.advanceTimeBy(ACTION_TOAST_MS + 500)
        compose.waitForIdle()

        compose.onNodeWithText(FAILED).assertExists()
    }

    @Test
    fun `the failed note goes 5 s after it shows`() {
        captions = CaptionSource { CaptionLookup.Failed }
        captionsLanguage("en")
        play()
        // The chrome holds the corner until its idle hide; the note's 5 s start then.
        compose.mainClock.advanceTimeBy(PlayerChromePolicy.HIDE_AFTER_IDLE_MS + 4_000)
        compose.waitForIdle()
        compose.onNodeWithText(FAILED).assertExists()

        compose.mainClock.advanceTimeBy(1_500)
        compose.waitForIdle()

        compose.onNodeWithText(FAILED).assertDoesNotExist()
    }

    @Test
    fun `a skip prompt keeps the corner, and the failed note shows once it goes`() {
        captions = CaptionSource { CaptionLookup.Failed }
        captionsLanguage("en")
        service.segments = runBlocking { RecordedSegments.lookup() }
        play(atMs = 60_000)

        compose.pressBack()
        compose.onNodeWithText(PROMPT_SKIP).assertExists()
        compose.onNodeWithText(FAILED).assertDoesNotExist()
        remoteBack()

        compose.onNodeWithText(PROMPT_SKIP).assertDoesNotExist()
        compose.onNodeWithText(FAILED).assertExists()
    }
}
